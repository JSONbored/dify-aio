"""Refresh the AIO template input from Dify's versioned, per-service env files."""

from __future__ import annotations

import json
import re
from pathlib import Path
from urllib.request import Request, urlopen

from generate_dify_template import ENUM_DEFAULTS, NON_SECRET_TARGETS

ROOT = Path(__file__).resolve().parents[1]
ASSIGNMENT = re.compile(r"^(#\s*)?([A-Z][A-Z0-9_]*)=(.*)$")


def fetch(url: str) -> str:
    request = Request(url, headers={"User-Agent": "dify-aio-upstream-inventory"})
    with urlopen(
        request, timeout=45
    ) as response:  # nosec B310 - fixed GitHub HTTPS origins
        return response.read().decode()


def main() -> None:
    version = re.search(
        r"(?m)^ARG UPSTREAM_DIFY_VERSION=([\d.]+)$", (ROOT / "Dockerfile").read_text()
    )[1]
    tree = json.loads(
        fetch(
            f"https://api.github.com/repos/langgenius/dify/git/trees/{version}?recursive=1"
        )
    )
    if tree["truncated"]:
        raise ValueError("Incomplete Dify repository tree")
    files = sorted(
        blob["path"]
        for blob in tree["tree"]
        if blob["path"].startswith("docker/envs/")
        and blob["path"].endswith((".defaults", ".env.example"))
    )
    if "docker/envs/core-services/api-worker.defaults" not in files:
        raise ValueError(
            "Missing core API and worker settings for the selected release"
        )
    values = {}
    for path in [*files, "docker/.env.example", "api/.env.example"]:
        comments = []
        for line in fetch(
            f"https://raw.githubusercontent.com/langgenius/dify/{version}/{path}"
        ).splitlines():
            line = line.strip()
            match = ASSIGNMENT.fullmatch(line)
            if not match:
                if line.startswith("#"):
                    comments.append(line)
                else:
                    comments = []
                continue
            commented, key, value = match.groups()
            # Compose expands its own expressions before passing them to services.
            # Never put expressions, development credentials, or illustrative
            # values from commented examples into users' Unraid settings.
            self_default = re.fullmatch(r"\$\{" + key + r":?-(.*?)\}", value)
            if self_default:
                value = self_default[1]
            if "$" in value or (
                commented and key not in NON_SECRET_TARGETS and key not in ENUM_DEFAULTS
            ):
                value = ""
            rank = (
                0
                if path.startswith("docker/") and not commented
                else 1 if commented else 2
            )
            if key not in values or rank < values[key][0]:
                values[key] = (rank, [*comments, f"{key}={value}"])
            comments = []
    output = [
        f"# Dify {version} service configuration inventory. Generated by scripts/refresh_upstream_inventory.py."
    ]
    for key in sorted(values):
        output.extend(["", *values[key][1]])
    (ROOT / "docs/upstream/dify.env.example").write_text("\n".join(output) + "\n")


if __name__ == "__main__":
    main()
